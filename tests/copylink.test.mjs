// Test: buton „Copiază linkul” lângă fiecare link de canal; nu deschide nimic, copiază adresa.
import {createRequire} from 'node:module';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const require = createRequire(process.env.PW_ROOT || import.meta.url);
const {chromium} = require('playwright');
const here = path.dirname(fileURLToPath(import.meta.url));
const FILE = 'file://' + path.resolve(here, '..', 'index.html');
let ok = 0, bad = 0;
const t = (n, c, x) => { if (c) { ok++; console.log('  ok  ' + n); } else { bad++; console.log('  FAIL ' + n + (x ? ' :: ' + JSON.stringify(x) : '')); } };
const b = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox']});
const ctx = await b.newContext({locale: 'ro-RO', permissions: ['clipboard-read', 'clipboard-write']});
const hosts = new Set();
await ctx.route(/^https?:/, (r) => {
  const u = new URL(r.request().url()); hosts.add(u.hostname);
  if (u.hostname === 'archive.org') return r.fulfill({status: 200, contentType: 'application/json', headers: {'access-control-allow-origin': '*'}, body: JSON.stringify({archived_snapshots: {}})});
  return r.fulfill({status: 200, contentType: 'text/html', body: '<!doctype html><title>s</title>'});
});
const p = await ctx.newPage(); const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
await p.goto(FILE); await p.waitForTimeout(500);
t('fără butoane înainte de scanare', await p.locator('.cplink').count() === 0);
await p.fill('#handleInput', 'jack'); await p.click('#txtScanBtn'); await p.waitForTimeout(1200);
const n = await p.locator('.cplink').count();
t('buton pentru fiecare link (direct 2 + arhivă 3 + index 2 = 7)', n === 7, n);
const pages = ctx.pages().length;
await p.locator('.cplink').first().click(); await p.waitForTimeout(300);
t('copiază linkul X', (await p.evaluate(() => navigator.clipboard.readText())) === 'https://x.com/jack');
t('stare „copiat”', (await p.textContent('#linkCopyStatus')).length > 0);
t('nu s-a deschis nicio filă', ctx.pages().length === pages);
await p.locator('.cplink').nth(6).click(); await p.waitForTimeout(300);
t('copiază linkul Bing', /^https:\/\/www\.bing\.com\/search\?q=/.test(await p.evaluate(() => navigator.clipboard.readText())));
await p.click('.langbtn[data-lang=en]'); await p.waitForTimeout(300);
t('etichetă tradusă (en)', (await p.textContent('.cplink')) === 'Copy link' && await p.locator('.cplink').count() === 7);
t('niciun fetch către x.com / bing / google', ![...hosts].some((h) => /x\.com|bing|google/.test(h)), [...hosts]);
t('fără pageerror', errs.length === 0, errs);
await b.close();
console.log('\n' + ok + ' ok, ' + bad + ' eșuate');
process.exit(bad ? 1 : 0);
